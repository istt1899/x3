def clip(tmp):
    """The test clip: 854x480 H.264 (B-frames, 1 s GOP) at 30 fps, 1801 frames, AAC-LC stereo."""
    p = os.path.join(tmp, 'clip.mp4')
    if not os.path.exists(p):
        ff('-f', 'lavfi', '-i', 'testsrc2=size=854x480:rate=30', '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=44100',
           '-frames:v', '1801', '-t', '60.04', '-c:v', 'libx264', '-preset', 'veryfast', '-bf', '2', '-g', '30',
           '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-ac', '2', '-b:a', '128k', p)
    return p


def ff(*args):
    subprocess.run([FF, '-v', 'error', '-y', *args], check=True)


def packets(path, sel):
    out = subprocess.run([FFPROBE, '-v', 'error', '-select_streams', sel, '-show_entries',
                          'packet=size,duration', '-of', 'csv=p=0', path],
                         check=True, capture_output=True, text=True).stdout
    return [line.split(',')[:2] for line in out.split()]


def probe(path, entries):
    return json.loads(subprocess.run([FFPROBE, '-v', 'error', '-show_entries', entries, '-of', 'json', path],
                                     check=True, capture_output=True, text=True, encoding='utf-8').stdout)


def decoded(path):
    """the decoded audio's MD5 (ffmpeg's md5 muxer)"""
    return subprocess.run([FF, '-v', 'error', '-i', path, '-map', '0:a:0', '-f', 'md5', '-'],
                          check=True, capture_output=True, text=True).stdout.strip()


def atoms(path):
    with open(path, 'rb') as f:
        return [t.decode() for t, _, _ in ytfetch.boxes(f.read())]


def read_records(path):
    _, recs = mgyi.read_index(path)
    return [(r[0], r[1], r[2], r[3]) for r in recs]


class Pipeline:
    """Shared checks: our files vs the old ffmpeg/mgyi pipeline run on the same source files."""

    def check_video(self, src_mp4, out_dir, tmp):
        ref = os.path.join(tmp, 'ref.h264')
        ff('-i', src_mp4, '-map', '0:v:0', '-c', 'copy', '-bsf:v', 'h264_mp4toannexb', '-f', 'h264', ref)
        ref_idx = os.path.join(tmp, 'ref_index.bin')
        st, pk, _ = mgyi.build_index(src_mp4, ref, ref_idx)
        mine = os.path.join(out_dir, 'video.h264')
        with open(mine, 'rb') as a, open(ref, 'rb') as b:
            self.assertTrue(a.read() == b.read(), 'video.h264 differs from h264_mp4toannexb output')
        hdr, _ = mgyi.validate(os.path.join(out_dir, 'index.bin'), mine, len(pk))
        ref_hdr, _ = mgyi.read_index(ref_idx)
        self.assertEqual(hdr, ref_hdr)
        mine_r, ref_r = read_records(os.path.join(out_dir, 'index.bin')), read_records(ref_idx)
        self.assertEqual([r[:3] for r in mine_r], [r[:3] for r in ref_r])  # pts_ms, pos, size
        # key: we use the trun sync flag; ffprobe also flags open-GOP I-frames with a recovery-point SEI.
        # Those have no SPS, so ytdec's seek_point skips them either way: keys must agree where an SPS is.
        with open(mine, 'rb') as f:
            buf = f.read()
        sps = [any(t == 7 for _, t, _ in mgyi.nal_starts(buf[r[1]:r[1] + r[2]])) for r in mine_r]
        self.assertEqual([r[3] for r, s in zip(mine_r, sps) if s], [r[3] for r, s in zip(ref_r, sps) if s])
        self.assertTrue(all(b[3] for a, b in zip(mine_r, ref_r) if a[3]), 'a key of ours is not a key to ffprobe')
        self.extra_keys = sum(b[3] and not a[3] for a, b in zip(mine_r, ref_r))
        return hdr

    def check_audio(self, src_m4a, out_m4a):
        a = atoms(out_m4a)
        self.assertLess(a.index('moov'), a.index('mdat'), a)
        actual, original = packets(out_m4a, 'a:0'), packets(src_m4a, 'a:0')
        self.assertEqual([p[1] for p in actual], [p[1] for p in original])
        # Older ffprobe estimates the boundary durations of fragmented AAC differently.
        inner = slice(1, -1) if original[0][0] == 'N/A' else slice(None)
        self.assertEqual([p[0] for p in actual[inner]], [p[0] for p in original[inner]])
        self.assertEqual(decoded(out_m4a), decoded(src_m4a))
        r = subprocess.run([FF, '-v', 'error', '-i', out_m4a, '-f', 'null', '-'], capture_output=True, text=True)
        self.assertEqual((r.returncode, r.stderr), (0, ''))

    def check_head(self, head, full_m4a, ms):
        """head: a valid plain MP4 (ffprobe, ffmpeg decode clean) of the first packets of full_m4a, ms long"""
        self.assertEqual(atoms(head), ['ftyp', 'moov', 'mdat'])
        hp, fp = packets(head, 'a:0'), packets(full_m4a, 'a:0')
        self.assertTrue(hp and hp == fp[:len(hp)] and len(hp) < len(fp), (len(hp), len(fp)))
        dur = float(subprocess.run([FFPROBE, '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', head],
                                   check=True, capture_output=True, text=True).stdout)
        self.assertAlmostEqual(dur, ms / 1000, delta=0.05)
        r = subprocess.run([FF, '-v', 'error', '-i', head, '-f', 'null', '-'], capture_output=True, text=True)
        self.assertEqual((r.returncode, r.stderr), (0, ''))


class Offline(unittest.TestCase, Pipeline):
    @classmethod
    def setUpClass(cls):
        os.makedirs(TMP, exist_ok=True)
        cls.tmp = tempfile.mkdtemp(dir=TMP)
        cls.v = os.path.join(cls.tmp, 'v.mp4')
        cls.a = os.path.join(cls.tmp, 'a.m4a')
        ff('-i', clip(TMP), '-map', '0:v:0', '-c', 'copy', *FRAG, cls.v)
        ff('-i', clip(TMP), '-map', '0:a:0', '-c', 'copy', *FRAG, cls.a)

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp)

    def test_video_demux(self):
        out = tempfile.mkdtemp(dir=self.tmp)
        seen = []
        with open(self.v, 'rb') as f:
            n, size, ms = ytfetch.demux_video(f, out, None, lambda *x: seen.append(x))
        self.assertEqual(sorted(os.listdir(out)), ['index.bin', 'video.h264'])
        hdr = self.check_video(self.v, out, self.tmp)
        self.assertEqual(hdr, dict(w=854, h=480, fps=(30, 1), n=1801))
        self.assertEqual((n, seen[-1]), (1801, (ms, n, size)))

    def test_video_seek_points_have_sps(self):
        out = tempfile.mkdtemp(dir=self.tmp)
        with open(self.v, 'rb') as f:
            ytfetch.demux_video(f, out, None, lambda *x: None)
        with open(os.path.join(out, 'video.h264'), 'rb') as f:
            buf = f.read()
        recs = read_records(os.path.join(out, 'index.bin'))
        idr = [r for r in recs if any(t == 5 for _, t, _ in mgyi.nal_starts(buf[r[1]:r[1] + r[2]]))]
        self.assertTrue(idr and all(r[3] for r in idr))
        self.assertTrue(all(any(t == 7 for _, t, _ in mgyi.nal_starts(buf[r[1]:r[1] + r[2]])) for r in idr))

    def test_truncated_stream_keeps_part(self):
        out = tempfile.mkdtemp(dir=self.tmp)
        with open(self.v, 'rb') as f:
            data = f.read()
        with self.assertRaises(ValueError):
            ytfetch.demux_video(io.BytesIO(data[:len(data) // 2]), out, None, lambda *x: None)
        self.assertIn('video.h264.part', os.listdir(out))
        self.assertGreater(ytfetch.validate(os.path.join(out, 'index.bin'), os.path.join(out, 'video.h264.part')), 0)

    def test_audio_flatten(self):
        out = os.path.join(self.tmp, 'flat.m4a')
        ytfetch.flatten_m4a(self.a, out)
        self.check_audio(self.a, out)
        self.assertEqual(atoms(out), ['ftyp', 'moov', 'mdat'])

    def test_audio_head_of_a_prefix(self):
        """the first half written, the rest zeros (ranged_get's holes): a head of the samples in that half"""
        with open(self.a, 'rb') as f:
            data = f.read()
        part, head, flat = (os.path.join(self.tmp, n) for n in ('half.m4a', 'head.m4a', 'flat_ref.m4a'))
        limit = len(data) // 2
        with open(part, 'wb') as f:
            f.write(data[:limit] + bytes(len(data) - limit))
        n, ms = ytfetch.flatten_m4a(part, head, limit=limit)
        self.assertEqual(n, os.path.getsize(head))
        self.assertTrue(20000 < ms < 40000, ms)  # half of the 60 s clip
        ytfetch.flatten_m4a(self.a, flat)
        self.check_head(head, flat, ms)
        with self.assertRaises(ValueError):
            ytfetch.flatten_m4a(part, head, limit=100)  # not even the moov
        plain = os.path.join(self.tmp, 'plain_h.m4a')
        ff('-i', clip(TMP), '-map', '0:a:0', '-c', 'copy', '-movflags', '+faststart', plain)
        self.assertIsNone(ytfetch.flatten_m4a(plain, head, limit=os.path.getsize(plain) // 2))

    def test_audio_tags(self):
        """the car's player reads the title, artist and cover from the file: iTunes tags in the moov, which a
        reader (ffprobe) finds; the same audio, decoded bit for bit, as without them (the offsets moved too)"""
        jpg = os.path.join(self.tmp, 'cover.jpg')
        ff('-f', 'lavfi', '-i', 'color=red:size=320x180', '-frames:v', '1', jpg)
        with open(jpg, 'rb') as f:
            cover = f.read()
        plain, out = os.path.join(self.tmp, 'untagged.m4a'), os.path.join(self.tmp, 'tagged.m4a')
        ytfetch.flatten_m4a(self.a, plain)
        ytfetch.flatten_m4a(self.a, out, udta=ytfetch.tags_udta('Поправка a B58 — Café', 'Night Garage', cover))
        self.assertEqual(atoms(out), ['ftyp', 'moov', 'mdat'])
        self.assertEqual(decoded(out), decoded(plain), 'the same audio, every sample where the moov says')
        self.assertEqual(probe(out, 'format_tags=title,artist')['format']['tags'], {'title': 'Поправка a B58 — Café', 'artist': 'Night Garage'})
        pics = [s for s in probe(out, 'stream=codec_name:stream_disposition=attached_pic')['streams'] if s['disposition']['attached_pic']]
        self.assertEqual([s['codec_name'] for s in pics], ['mjpeg'], 'the cover, as an attached picture')
        # the head (a prefix of the download) carries them too
        with open(self.a, 'rb') as f:
            data = f.read()
        part, head = os.path.join(self.tmp, 'half_t.m4a'), os.path.join(self.tmp, 'head_t.m4a')
        with open(part, 'wb') as f:
            f.write(data[:len(data) // 2] + bytes(len(data) - len(data) // 2))
        ytfetch.flatten_m4a(part, head, limit=len(data) // 2, udta=ytfetch.tags_udta('Head', 'Chan'))
        self.assertEqual(probe(head, 'format_tags=title,artist')['format']['tags'], {'title': 'Head', 'artist': 'Chan'})

    def test_audio_plain_is_copied(self):
        plain, out = os.path.join(self.tmp, 'plain.m4a'), os.path.join(self.tmp, 'plain_out.m4a')
        ff('-i', clip(TMP), '-map', '0:a:0', '-c', 'copy', '-movflags', '+faststart', plain)
        ytfetch.flatten_m4a(plain, out)
        with open(plain, 'rb') as a, open(out, 'rb') as b:
            self.assertEqual(a.read(), b.read())


class Tags(unittest.TestCase):
    @staticmethod
    def items(u):
        """udta > meta (a full box) > hdlr mdir + ilst > {item: (data type, value)}"""
        (t, s, e), = ytfetch.boxes(u)
        assert t == b'udta'
        (t, s, e), = ytfetch.boxes(u, s, e)
        assert t == b'meta'
        hdlr, ilst = ytfetch.boxes(u, s + 4, e)
        assert (hdlr[0], u[hdlr[1] + 8:hdlr[1] + 12], ilst[0]) == (b'hdlr', b'mdir', b'ilst')
        out = {}
        for t, s, e in ytfetch.boxes(u, ilst[1], ilst[2]):
            (d, ds, de), = ytfetch.boxes(u, s, e)
            assert d == b'data'
            out[t] = (struct.unpack_from('>I', u, ds)[0], u[ds + 8:de])
        return out

    def test_udta_layout(self):
        self.assertEqual(self.items(ytfetch.tags_udta('Title', 'Artist', b'\xff\xd8 a jpeg')),
                         {b'\xa9nam': (1, b'Title'), b'\xa9ART': (1, b'Artist'), b'covr': (13, b'\xff\xd8 a jpeg')})
        self.assertEqual(self.items(ytfetch.tags_udta('Кофе — Café', None, None)), {b'\xa9nam': (1, 'Кофе — Café'.encode())})
        self.assertEqual(self.items(ytfetch.tags_udta(None, 'A', b'\x89PNG\r\n\x1a\nx')), {b'\xa9ART': (1, b'A'), b'covr': (14, b'\x89PNG\r\n\x1a\nx')})
        self.assertEqual(ytfetch.tags_udta(), b'', 'nothing to say: no box')
        self.assertEqual(len(self.items(ytfetch.tags_udta('x' * 300))[b'\xa9nam'][1]), 255, 'a long title cut')

    def test_cover_is_a_jpeg_or_nothing(self):
        bodies = {'/ok': b'\xff\xd8' + b'j' * 100, '/png': b'\x89PNG\r\n\x1a\n' + b'p' * 100,
                  '/big': b'\xff\xd8' + bytes(ytfetch.COVER_MAX), '/missing': None}

        class H(http.server.BaseHTTPRequestHandler):
            def do_GET(self):
                b = bodies.get(self.path)
                if b is None:
                    self.send_error(404)
                    return
                self.send_response(200)
                self.send_header('Content-Length', str(len(b)))
                self.end_headers()
                self.wfile.write(b)

            def log_message(self, *a):
                pass

        srv = http.server.ThreadingHTTPServer(('127.0.0.1', 0), H)
        threading.Thread(target=srv.serve_forever, daemon=True).start()
        old, ytfetch.COVER_URL = ytfetch.COVER_URL, f'http://127.0.0.1:{srv.server_port}/{{}}'
        try:
            self.assertEqual(ytfetch.fetch_cover('ok'), bodies['/ok'])
            for p in ('png', 'big', 'missing'):
                self.assertIsNone(ytfetch.fetch_cover(p), p)
        finally:
            ytfetch.COVER_URL = old
            srv.shutdown()
            srv.server_close()


class _Ranges(http.server.BaseHTTPRequestHandler):
    """GET with Range: bytes=s-e -> 206 of the server's data; no Range -> 200 (which ranged_get refuses)"""
    def do_GET(self):  # noqa: N802
        data, rng = self.server.data, self.headers.get('Range')
        self.server.seen.append((rng, self.headers.get('User-Agent')))
        if rng and self.server.ranges:
            s, e = (int(x) for x in rng.split('=')[1].split('-'))
            body, code = data[s:e + 1], 206
        else:
            body, code = data, 200
        self.send_response(code)
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        try:
            self.wfile.write(body)
        except ConnectionError:
            pass  # ranged_get hangs up on a 200

    def log_message(self, *a):
        pass


class Ranged(unittest.TestCase, Pipeline):
    @classmethod
    def setUpClass(cls):
        os.makedirs(TMP, exist_ok=True)
        cls.tmp = tempfile.mkdtemp(dir=TMP)
        cls.a = os.path.join(cls.tmp, 'a.m4a')
        ff('-i', clip(TMP), '-map', '0:a:0', '-c', 'copy', *FRAG, cls.a)
        with open(cls.a, 'rb') as f:
            data = f.read()
        cls.srv = http.server.ThreadingHTTPServer(('127.0.0.1', 0), _Ranges)
        cls.srv.data, cls.srv.seen, cls.srv.ranges = data, [], True
        threading.Thread(target=cls.srv.serve_forever, daemon=True).start()
        cls.url = f'http://127.0.0.1:{cls.srv.server_address[1]}/a'

    @classmethod
    def tearDownClass(cls):
        cls.srv.shutdown()
        shutil.rmtree(cls.tmp)

    def get(self, conns, **kw):
        out, seen = os.path.join(self.tmp, f'got{conns}.m4a'), []
        ytfetch.ranged_get(self.url, {'User-Agent': 'UA-1'}, out, len(self.srv.data), lambda p, d: seen.append((p, d)),
                           conns=conns, **kw)
        with open(out, 'rb') as f:
            return f.read(), seen

    def test_parallel_is_byte_identical_to_one_stream(self):
        one, _ = self.get(1, first=len(self.srv.data), chunk=len(self.srv.data))  # one request, the whole file
        four, seen = self.get(4, first=50000, chunk=70000)
        self.assertEqual(one, self.srv.data)
        self.assertEqual(four, one)
        self.assertEqual([d for _, d in seen], sorted(d for _, d in seen))
        self.assertEqual([p for p, _ in seen], sorted(p for p, _ in seen), 'prefix only grows')
        self.assertEqual(seen[-1], (len(one), len(one)))
        self.assertEqual(len(seen), 1 + -(-(len(one) - 50000) // 70000))
        self.assertTrue(all(ua == 'UA-1' for _, ua in self.srv.seen[-len(seen):]), 'the format\'s headers on every range')

    def test_gate_one_connection_until_set(self):
        gate, n = threading.Event(), len(self.srv.data)
        out, seen = os.path.join(self.tmp, 'gated.m4a'), []

        def on_chunk(p, d):
            seen.append(threading.active_count())
            if len(seen) == 3:
                gate.set()
        ytfetch.ranged_get(self.url, {}, out, n, on_chunk, conns=4, first=50000, chunk=70000, gate=gate)
        with open(out, 'rb') as f:
            self.assertEqual(f.read(), self.srv.data)
        self.assertEqual(seen[:3], sorted(seen[:3]), 'in order while gated')
        self.srv.ranges = False
        try:
            with self.assertRaises(OSError):  # an error releases the gated workers: no hang
                ytfetch.ranged_get(self.url, {}, out, n, None, conns=4, first=50000, chunk=70000, gate=threading.Event())
        finally:
            self.srv.ranges = True

    def test_no_range_support_fails(self):
        self.srv.ranges = False
        try:
            with self.assertRaises(OSError):
                self.get(2, first=50000, chunk=70000)
        finally:
            self.srv.ranges = True

    def test_audio_ranged_writes_head_then_returns_src(self):
        out = tempfile.mkdtemp(dir=self.tmp)
        info = {'protocol': 'http', 'filesize': len(self.srv.data), 'url': self.url, 'http_headers': {}}

        class Ya:
            def process_ie_result(self, i, download):
                assert download is False
                return dict(i)
        buf, old = io.StringIO(), (ytfetch._out, ytfetch.HEAD_MIN_MS, ytfetch.AUDIO_FIRST, ytfetch.AUDIO_CHUNK)
        ytfetch._out, ytfetch.HEAD_MIN_MS = buf, 10000
        ytfetch.AUDIO_FIRST = ytfetch.AUDIO_CHUNK = 60000
        try:
            a = type('A', (), {'dir': out, 'proxy': None})()
            src = ytfetch.audio_ranged(a, Ya(), info, {'duration_s': 60})
        finally:
            ytfetch._out, ytfetch.HEAD_MIN_MS, ytfetch.AUDIO_FIRST, ytfetch.AUDIO_CHUNK = old
        evs = [json.loads(x) for x in buf.getvalue().splitlines()]
        heads = [e for e in evs if e['ev'] == 'audio_head']
        self.assertEqual(len(heads), 1, evs)
        self.assertGreaterEqual(heads[0]['ms'], 10000)
        self.assertEqual(sorted(os.listdir(out)), ['audio.head.m4a', 'audio.src.m4a'])
        with open(src, 'rb') as f:
            self.assertEqual(f.read(), self.srv.data)
        flat = os.path.join(out, 'flat.m4a')
        ytfetch.flatten_m4a(src, flat)
        self.check_head(os.path.join(out, 'audio.head.m4a'), flat, heads[0]['ms'])
        self.assertIsNone(ytfetch.audio_ranged(a, Ya(), dict(info, protocol='m3u8_native'), {'duration_s': 60}))
        self.srv.ranges = False  # every range answered 200: it fails, and leaves no src for yt-dlp to skip
        try:
            for n in os.listdir(out):
                os.remove(os.path.join(out, n))
            with self.assertRaises(OSError):
                ytfetch.audio_ranged(a, Ya(), info, {'duration_s': 60})
            self.assertEqual(os.listdir(out), [])
        finally:
            self.srv.ranges = True
        self.assertIsNone(ytfetch.audio_ranged(a, Ya(), dict(info, filesize=None), {'duration_s': 60}))


class Dns(unittest.TestCase):
    def setUp(self):
        self.orig = socket.getaddrinfo
        fd, self.lease = tempfile.mkstemp(dir=TMP)
        with os.fdopen(fd, 'w') as f:
            json.dump({'dns': ['1.1.1.1']}, f)

    def tearDown(self):
        socket.getaddrinfo = self.orig
        os.remove(self.lease)

    def test_lease_dns(self):
        try:
            ips = ytfetch.resolve_a('www.youtube.com', ['1.1.1.1'])
        except OSError as e:
            self.skipTest(f'no network: {e}')
        self.assertTrue(ips and all(socket.inet_aton(ip) for ip in ips))
        self.assertEqual(ytfetch.install_dns(self.lease), ['1.1.1.1'])
        self.assertIsNot(socket.getaddrinfo, self.orig)
        got = socket.getaddrinfo('www.youtube.com', 443, 0, socket.SOCK_STREAM)
        self.assertEqual({g[4][0] for g in got}, set(ips))
        self.assertEqual({(g[0], g[4][1]) for g in got}, {(socket.AF_INET, 443)})
        self.assertEqual(socket.getaddrinfo('127.0.0.1', 80)[0][4], ('127.0.0.1', 80))  # literal passes through
        self.assertEqual(socket.getaddrinfo('::1', 80, socket.AF_INET6)[0][4][0], '::1')
        with self.assertRaises(socket.gaierror):
            ytfetch.resolve_a('nonexistent.invalid', ['1.1.1.1'])

    def test_no_lease_keeps_resolver(self):
        self.assertEqual(ytfetch.install_dns(os.path.join(TMP, 'no-such-lease.json')), [])
        self.assertIs(socket.getaddrinfo, self.orig)


class ClockWrong(unittest.TestCase):
    def test_messages(self):
        import ssl
        e = ssl.SSLCertVerificationError(1, '[SSL: CERTIFICATE_VERIFY_FAILED] certificate verify failed: '
                                            'certificate is not yet valid (_ssl.c:1010)')
        m = ytfetch.clock_wrong(Exception('ERROR: [youtube] x: Unable to download API page: ' + str(e)))
        self.assertTrue(m.startswith("Wrong head unit clock (20"), m)
