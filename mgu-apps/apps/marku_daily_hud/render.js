function rgbaAlert(text, color) {
  const output = Buffer.alloc(W * H * 4);
  const bg = color === 'red' ? [70, 12, 12, 220] : [54, 38, 8, 220];
  for (let offset = 0; offset < output.length; offset += 4) output.set(bg, offset);
  const value = String(text || '').toUpperCase().replace(/[^A-Z0-9 .%+-]/g, '').slice(0, 12);
  const textWidth = value.length * 6 * SCALE - SCALE;
  let x0 = Math.max(18, Math.floor((W - textWidth) / 2));
  const y0 = Math.floor((H - 7 * SCALE) / 2);
  for (const char of value) {
    const glyph = GLYPHS[char] || GLYPHS[' '];
    glyph.forEach((row, gy) => row.split('').forEach((bit, gx) => {
      if (bit !== '1') return;
      for (let sy = 0; sy < SCALE; sy += 1) for (let sx = 0; sx < SCALE; sx += 1) {
        const x = x0 + gx * SCALE + sx, y = y0 + gy * SCALE + sy;
        if (x < 0 || x >= W || y < 0 || y >= H) continue;
        const offset = (y * W + x) * 4;
        output[offset] = 255; output[offset + 1] = 224; output[offset + 2] = 150; output[offset + 3] = 255;
      }
    }));
    x0 += 6 * SCALE;
  }
  return { width: W, height: H, pixels: output };
}

module.exports = { W, H, SCALE, GLYPHS, rgbaAlert };
